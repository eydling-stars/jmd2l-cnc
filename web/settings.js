const cfgEl = {};    // индекс → input
const dirty = new Set();
let cfgState = '';

function idOf(i) { return 'set' + i; }

function buildSettings() {
  const wrap = $('sets');
  wrap.innerHTML = '';
  for (const sec of SECTIONS) {
    const card = document.createElement('div');
    card.className = 'card';
    let html = '<h3>' + sec.title + '</h3>';
    for (const f of sec.fields) {
      const [i, label, min, max, step, unit] = f;
      const div = f[6] || 1, hint = f[7] || '', opts = f[8];
      const type = opts ? 'select' : (min === 0 && max === 1 ? 'checkbox' : 'number');
      // Единица или расшифровка значения — сразу справа от поля: оператор не
      // должен держать в голове, в чём измеряется введённое число. У списка
      // хвоста нет: слова вариантов и есть подпись поля.
      const tail = type === 'select' ? '' :
        '<span class="unit" title="' + (unit || hint) + '">' +
        (type === 'checkbox' ? hint : (unit || hint)) + '</span>';
      const field = type === 'select'
        ? '<select id="' + idOf(i) + '" data-i="' + i + '" title="' + hint + '">' +
          opts.map((o, k) => '<option value="' + k + '">' + o + '</option>').join('') + '</select>'
        : type === 'checkbox'
          ? '<input type="checkbox" id="' + idOf(i) + '" data-i="' + i + '">'
          : '<input type="number" id="' + idOf(i) + '" data-i="' + i + '" data-div="' + div +
            '" min="' + (min / div) + '" max="' + (max / div) + '" step="' + (step / div) + '">';
      html += '<label class="fld">' +
        '<span class="lbl">' + label + '</span>' + field + tail +
        '</label>';
    }
    if (sec.buttons) {
      for (const [name, fn] of sec.buttons) html += ' <button class="mini" data-act="' + name + '">' + name + '</button>';
    }
    html += '<div class="dim help">' + sec.help + '</div>';
    card.innerHTML = html;
    wrap.appendChild(card);
    if (sec.buttons) {
      card.querySelectorAll('[data-act]').forEach((b) => {
        b.onclick = sec.buttons.find((x) => x[0] === b.dataset.act)[1];
      });
    }
  }
  for (const el of wrap.querySelectorAll('[data-i]')) {
    el.onchange = () => {
      dirty.add(Number(el.dataset.i));
      cfgState = 'изменено (не применено)';
      $('btnSave').disabled = false;
      $('cfgState').textContent = cfgState;
    };
  }
  $('btnSave').onclick = saveSettings;
  $('btnRevert').onclick = () => cmd('T');
  $('btnDefaults').onclick = () => { cmd('TD'); cmd('T'); };
}

function fillSettings(v) {
  dirty.clear();
  cfgState = '';
  $('cfgState').textContent = '';
  $('btnSave').disabled = true;
  for (const el of document.querySelectorAll('[data-i]')) {
    const i = Number(el.dataset.i);
    const val = v[i];
    if (el.type === 'checkbox') el.checked = !!val;
    else if (el.tagName === 'SELECT') el.value = String(val);
    else {
      const div = Number(el.dataset.div) || 1;
      el.value = val === undefined ? '' : (div === 1 ? val : (val / div).toFixed(1));
    }
  }
}

// Одна кнопка: «Сохранить в плату». Кнопка «Применить без записи» убрана по
// требованию оператора — она требовала каждый раз подтверждать настройки заново,
// а нужно один раз выставить скорости хода и забыть. Скорости ползунков и
// длины хода сохраняются сами (saveLater в app.js).
function saveSettings() {
  const order = [...dirty].sort((a, b) => a - b);
  for (const i of order) {
    const el = $(idOf(i));
    const div = Number(el.dataset.div) || 1;
    const val = el.type === 'checkbox' ? (el.checked ? 1 : 0)
      : el.tagName === 'SELECT' ? parseInt(el.value, 10)
        : Math.round(parseFloat(el.value) * div);
    cmd('T ' + i + ' ' + val);
  }
  cmd('TS');
  setTimeout(() => cmd('T'), 50);   // покажем сохранённые (плата клампит за пределы)
  cfgState = 'сохранено в EEPROM';
  $('cfgState').textContent = cfgState;
}

buildSettings();